    def _record_decision(self, decision: Decision):
        """Record decision in metrics"""
        self.metrics.total_decisions += 1
        self.metrics.strategy_usage[decision.strategy] += 1
        
        # Update average confidence
        total_confidence = (
            self.metrics.average_confidence * (self.metrics.total_decisions - 1)
        )
        self.metrics.average_confidence = (
            (total_confidence + decision.confidence) / self.metrics.total_decisions
        )
    
    def _update_strategy_performance(
        self,
        strategy: ReasoningStrategy,
        validation_result: ValidationResult
    ):
        """Update strategy performance metrics based on validation"""
        perf = self.strategy_performance[strategy]
        perf["total"] += 1
        
        if validation_result.success:
            perf["successful"] += 1
        
        # Update average efficiency
        total_efficiency = perf["average_efficiency"] * (perf["total"] - 1)
        perf["average_efficiency"] = (
            (total_efficiency + validation_result.efficiency_score) / perf["total"]
        )