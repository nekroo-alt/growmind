    def _identify_risks(self, situation_type: SituationType, features: Dict[str, Any]) -> List[str]:
        """Identify risks in current situation"""
        risks = []
        
        if features["error_frequency"] > 0:
            risks.append("Recurring errors may indicate deeper issue")
        
        if features["resource_availability"] != "good":
            risks.append("Limited resources may cause failures")
        
        if features["progress_rate"] < 0.1:
            risks.append("Slow progress may indicate stuck state")
        
        return risks
    
